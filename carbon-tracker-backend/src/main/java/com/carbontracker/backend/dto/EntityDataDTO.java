package com.carbontracker.backend.dto;

import java.util.List;

public class EntityDataDTO {
    private String entity_id;
    private String entity_name;
    private String entity_type;
    private String phone;
    private String address;
    private String district;
    private String state;
    private String pin_code;
    private List<TransactionDataDTO> transactions;
	public String getEntity_id() {
		return entity_id;
	}
	public void setEntity_id(String entity_id) {
		this.entity_id = entity_id;
	}
	public String getEntity_name() {
		return entity_name;
	}
	public void setEntity_name(String entity_name) {
		this.entity_name = entity_name;
	}
	public String getEntity_type() {
		return entity_type;
	}
	public void setEntity_type(String entity_type) {
		this.entity_type = entity_type;
	}
	public String getPhone() {
		return phone;
	}
	public void setPhone(String phone) {
		this.phone = phone;
	}
	public String getAddress() {
		return address;
	}
	public void setAddress(String address) {
		this.address = address;
	}
	public String getDistrict() {
		return district;
	}
	public void setDistrict(String district) {
		this.district = district;
	}
	public String getState() {
		return state;
	}
	public void setState(String state) {
		this.state = state;
	}
	public String getPin_code() {
		return pin_code;
	}
	public void setPin_code(String pin_code) {
		this.pin_code = pin_code;
	}
	public List<TransactionDataDTO> getTransactions() {
		return transactions;
	}
	public void setTransactions(List<TransactionDataDTO> transactions) {
		this.transactions = transactions;
	}
}
